# Unanswerable items whose topic IS mentioned in passing (lexical overlap, no answer):
# the hardest refusals, since retrieval will surface plausible-looking chunks.
HARD_NEGATIVES = {1, 3, 4, 7, 9}


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    rows = []
    for i, (q, ref, sources, tags) in enumerate(ANSWERABLE, start=1):
        rows.append({"id": f"a{i:03d}", "question": q, "answerable": True, "reference_answer": ref,
                     "sources": [{"doc_id": d, "evidence": e} for d, e in sources], "tags": tags})
    for i, (q, absent) in enumerate(UNANSWERABLE, start=1):
        rows.append({"id": f"u{i:03d}", "question": q, "answerable": False, "reference_answer": "",
                     "sources": [], "absent_terms": absent,
                     "tags": ["unanswerable"] + (["hard-negative"] if i in HARD_NEGATIVES else [])})
    with OUT.open("w", encoding="utf-8") as fh:
        for r in rows:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"Wrote {len(rows)} items ({len(ANSWERABLE)} answerable, {len(UNANSWERABLE)} unanswerable) -> {OUT}")


if __name__ == "__main__":
    main()
